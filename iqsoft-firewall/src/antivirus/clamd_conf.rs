//! Generate clamd.conf from the AV settings (option 3).
//!
//! Why this matters for speed and for correctness:
//! * `TemporaryDirectory` on tmpfs: clamd writes every INSTREAM scan to a temp
//!   file, so on RAM it avoids slow flash writes. The tmpfs needs room for
//!   about `max_scan_mb` per concurrent scan. Create the directory at boot,
//!   e.g. with a tmpfiles.d line: `d /run/clamav/tmp 0750 clamav clamav -`
//! * `StreamMaxLength` and `MaxFileSize` follow `max_scan_mb`. If they are
//!   smaller than what the proxy sends, clamd either aborts the stream or
//!   silently skips the file, so the limits must never be below it.
//! * `MaxThreads` is higher than the CPU count because streaming sessions sit
//!   idle while a slow download arrives. Keep the proxy's number of
//!   concurrent streaming scans at or below `MaxThreads / 2` so that quick
//!   buffered scans always find a free thread.
//! * `ReadTimeout` is how long clamd waits for the next piece of a stream.
//!   Keep the proxy's upstream idle timeout below it.
//! * `ScanArchive` and `AlertEncrypted` come from the settings page, so those
//!   switches finally do something. Check the option name against the
//!   `clamd.conf.sample` of the ClamAV version in your image (older releases
//!   called it `ArchiveBlockEncrypted`).
//!
//! The file replaces the distribution's clamd.conf entirely, so it must carry
//! everything clamd needs. Reload clamd after writing it.

use crate::models::av::AvSettings;

pub struct ClamdFiles<'a> {
    pub user: &'a str,
    pub database_dir: &'a str,
    pub temp_dir: &'a str,
}

impl Default for ClamdFiles<'static> {
    fn default() -> Self {
        Self {
            user: "clamav",
            database_dir: "/var/lib/clamav",
            temp_dir: "/run/clamav/tmp",
        }
    }
}

/// One thread per CPU core, between 1 and 4. Pass the result to `render`.
pub fn recommended_threads() -> usize {
    std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(1)
        .clamp(1, 4)
}

pub fn render(settings: &AvSettings, threads: usize, files: &ClamdFiles<'_>) -> String {
    let mb = settings.max_scan_mb.clamp(1, 512);
    let threads = threads.clamp(1, 16);
    let scan_all = (mb * 4).min(4000);
    let yes_no = |on: bool| if on { "yes" } else { "no" };

    let lines = vec![
        "# Generated by iqsoft-firewall from the antivirus settings. Do not edit by hand."
            .to_string(),
        format!("User {}", files.user),
        format!("LocalSocket {}", settings.clamd_socket),
        "LocalSocketMode 660".to_string(),
        "FixStaleSocket yes".to_string(),
        format!("DatabaseDirectory {}", files.database_dir),
        format!("TemporaryDirectory {}", files.temp_dir),
        format!("MaxThreads {}", threads * 4),
        format!("MaxQueue {}", threads * 32),
        format!("StreamMaxLength {mb}M"),
        format!("MaxFileSize {mb}M"),
        format!("MaxScanSize {scan_all}M"),
        "MaxRecursion 8".to_string(),
        "MaxFiles 1000".to_string(),
        format!("ScanArchive {}", yes_no(settings.scan_archives)),
        format!("AlertEncrypted {}", yes_no(settings.block_encrypted_archives)),
        "ReadTimeout 300".to_string(),
        "CommandReadTimeout 30".to_string(),
        "SelfCheck 3600".to_string(),
    ];

    let mut text = lines.join("\n");
    text.push('\n');
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn defaults() -> AvSettings {
        serde_json::from_str("{}").unwrap()
    }

    #[test]
    fn limits_follow_the_settings() {
        let mut settings = defaults();
        settings.max_scan_mb = 50;
        settings.scan_archives = false;
        settings.block_encrypted_archives = true;

        let text = render(&settings, 2, &ClamdFiles::default());

        assert!(text.contains("StreamMaxLength 50M\n"));
        assert!(text.contains("MaxFileSize 50M\n"));
        assert!(text.contains("MaxScanSize 200M\n"));
        assert!(text.contains("ScanArchive no\n"));
        assert!(text.contains("AlertEncrypted yes\n"));
        assert!(text.contains("MaxThreads 8\n"));
        assert!(text.contains("TemporaryDirectory /run/clamav/tmp\n"));
        assert!(text.contains(&format!("LocalSocket {}\n", settings.clamd_socket)));
    }

    #[test]
    fn extreme_values_are_clamped() {
        let mut settings = defaults();
        settings.max_scan_mb = 100_000;

        let text = render(&settings, 0, &ClamdFiles::default());

        assert!(text.contains("StreamMaxLength 512M\n"));
        assert!(text.contains("MaxScanSize 2048M\n"));
        assert!(text.contains("MaxThreads 4\n"));
    }

    #[test]
    fn thread_recommendation_is_sane() {
        let n = recommended_threads();
        assert!((1..=4).contains(&n));
    }
}
