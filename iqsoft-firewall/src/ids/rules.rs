//! Keeps Suricata's signature file up to date.
//!
//! Signatures come from `suricata-update` (Emerging Threats Open by default).
//! The overrides saved in the database are written into the three small files
//! that `suricata-update` reads, so they survive every update:
//!
//!   iqsoft-disable.conf  - signatures switched off
//!   iqsoft-drop.conf     - signatures turned into "drop" (blocks in IPS mode)
//!   iqsoft-modify.conf   - signatures forced back to "alert only"
//!
//! This file only downloads and prepares the signatures. Telling a running
//! Suricata to load them is done by the commit code.

use crate::{
    ids::config::SuricataFiles, models::ids::IdsRuleOverride,
    repository::ids_repository::IdsRepository,
};
use serde::Serialize;
use sqlx::SqlitePool;
use std::{
    fs,
    io::{BufRead, BufReader},
    path::Path,
    sync::Mutex as StdMutex,
    time::{Duration, SystemTime, UNIX_EPOCH},
};

const DISABLE_CONF: &str = "iqsoft-disable.conf";
const DROP_CONF: &str = "iqsoft-drop.conf";
const MODIFY_CONF: &str = "iqsoft-modify.conf";

const UPDATE_TIMEOUT: Duration = Duration::from_secs(15 * 60);
const MAX_MESSAGE_CHARS: usize = 1500;
const MESSAGE_TAIL_LINES: usize = 12;

static UPDATE_LOCK: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());
static LAST_UPDATE: StdMutex<Option<RuleUpdateStatus>> = StdMutex::new(None);

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct RuleUpdateStatus {
    pub finished_at: i64,
    pub success: bool,
    pub message: String,
    pub total_rules: Option<i64>,
    pub enabled_rules: Option<i64>,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct RuleFileInfo {
    pub path: String,
    pub exists: bool,
    pub size_bytes: u64,
    pub modified_at: Option<i64>,
    pub rule_count: i64,
}

fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

/// The result of the most recent update since the firewall started, if any.
pub fn last_update() -> Option<RuleUpdateStatus> {
    LAST_UPDATE.lock().ok().and_then(|guard| guard.clone())
}

fn remember(status: &RuleUpdateStatus) {
    if let Ok(mut guard) = LAST_UPDATE.lock() {
        *guard = Some(status.clone());
    }
}

// ---------- the three override files ----------

fn sorted(overrides: &[IdsRuleOverride], action: &str) -> Vec<i64> {
    let mut sids: Vec<i64> = overrides
        .iter()
        .filter(|rule| rule.action == action)
        .map(|rule| rule.sid)
        .collect();

    sids.sort_unstable();
    sids.dedup();
    sids
}

const HEADER: &str = "# Generated by iqsoft-firewall from the IDS/IPS rule overrides. Do not edit by hand.\n";

pub fn render_disable_conf(overrides: &[IdsRuleOverride]) -> String {
    let mut out = String::from(HEADER);

    for sid in sorted(overrides, "disable") {
        out.push_str(&format!("{}\n", sid));
    }

    out
}

pub fn render_drop_conf(overrides: &[IdsRuleOverride]) -> String {
    let mut out = String::from(HEADER);

    for sid in sorted(overrides, "drop") {
        out.push_str(&format!("{}\n", sid));
    }

    out
}

/// "alert" overrides: some signatures are shipped as "drop", this turns them back into plain alerts.
pub fn render_modify_conf(overrides: &[IdsRuleOverride]) -> String {
    let mut out = String::from(HEADER);

    for sid in sorted(overrides, "alert") {
        out.push_str(&format!("{} \"^(drop|reject)\" \"alert\"\n", sid));
    }

    out
}

fn config_path(files: &SuricataFiles<'_>, name: &str) -> String {
    format!("{}/{}", files.config_dir.trim_end_matches('/'), name)
}

fn write_atomic(path: &str, text: &str) -> Result<(), String> {
    let temp = format!("{}.tmp", path);

    fs::write(&temp, text).map_err(|e| format!("Failed to write {}: {}", temp, e))?;

    fs::rename(&temp, path).map_err(|e| {
        let _ = fs::remove_file(&temp);
        format!("Failed to replace {}: {}", path, e)
    })
}

pub fn write_override_files(
    files: &SuricataFiles<'_>,
    overrides: &[IdsRuleOverride],
) -> Result<(), String> {
    fs::create_dir_all(files.config_dir)
        .map_err(|e| format!("Failed to create {}: {}", files.config_dir, e))?;

    write_atomic(
        &config_path(files, DISABLE_CONF),
        &render_disable_conf(overrides),
    )?;
    write_atomic(&config_path(files, DROP_CONF), &render_drop_conf(overrides))?;
    write_atomic(
        &config_path(files, MODIFY_CONF),
        &render_modify_conf(overrides),
    )?;

    Ok(())
}

// ---------- the signature file ----------

/// Makes sure a signature file exists, so Suricata can start before the first
/// download has finished. It is an empty file until `update_rules` replaces it.
pub fn ensure_rules_file(files: &SuricataFiles<'_>) -> Result<(), String> {
    fs::create_dir_all(files.rule_dir)
        .map_err(|e| format!("Failed to create {}: {}", files.rule_dir, e))?;

    let path = files.rules_path();

    if Path::new(&path).exists() {
        return Ok(());
    }

    fs::write(&path, "# No signatures yet. Run a rule update to download them.\n")
        .map_err(|e| format!("Failed to create {}: {}", path, e))
}

fn count_rules_in_file(path: &str) -> std::io::Result<i64> {
    let file = fs::File::open(path)?;
    let mut count = 0i64;

    for line in BufReader::new(file).split(b'\n') {
        let line = line?;
        let text = String::from_utf8_lossy(&line);
        let text = text.trim_start();

        if ["alert ", "drop ", "reject ", "pass "]
            .iter()
            .any(|action| text.starts_with(action))
        {
            count += 1;
        }
    }

    Ok(count)
}

/// Size, age and number of active signatures in the signature file.
pub async fn rule_file_info(files: &SuricataFiles<'_>) -> RuleFileInfo {
    let path = files.rules_path();

    let meta = match tokio::fs::metadata(&path).await {
        Ok(meta) => meta,
        Err(_) => {
            return RuleFileInfo {
                path,
                exists: false,
                size_bytes: 0,
                modified_at: None,
                rule_count: 0,
            };
        }
    };

    let modified_at = meta
        .modified()
        .ok()
        .and_then(|t| t.duration_since(UNIX_EPOCH).ok())
        .map(|d| d.as_secs() as i64);

    let counted_path = path.clone();

    let rule_count = tokio::task::spawn_blocking(move || count_rules_in_file(&counted_path))
        .await
        .ok()
        .and_then(Result::ok)
        .unwrap_or(0);

    RuleFileInfo {
        path,
        exists: true,
        size_bytes: meta.len(),
        modified_at,
        rule_count,
    }
}

// ---------- running suricata-update ----------

fn number_after(line: &str, key: &str) -> Option<i64> {
    let rest = &line[line.find(key)? + key.len()..];

    let digits: String = rest
        .trim_start()
        .chars()
        .take_while(|c| c.is_ascii_digit())
        .collect();

    digits.parse().ok()
}

/// Reads the totals out of suricata-update's own summary lines.
pub fn parse_counts(output: &str) -> (Option<i64>, Option<i64>) {
    let mut total = None;
    let mut enabled = None;

    for line in output.lines() {
        if line.contains("Writing rules to") {
            total = number_after(line, "total:").or(total);
            enabled = number_after(line, "enabled:").or(enabled);
        } else if total.is_none() && line.contains("Loaded") && line.contains("rules") {
            total = number_after(line, "Loaded");
        }
    }

    (total, enabled)
}

fn tail_of(output: &str) -> String {
    let lines: Vec<&str> = output
        .lines()
        .map(str::trim_end)
        .filter(|line| !line.is_empty())
        .collect();

    let from = lines.len().saturating_sub(MESSAGE_TAIL_LINES);
    let joined = lines[from..].join("\n");

    joined.chars().take(MAX_MESSAGE_CHARS).collect()
}

fn update_args(files: &SuricataFiles<'_>) -> Vec<String> {
    vec![
        "--no-reload".to_string(),
        "--suricata-conf".to_string(),
        config_path(files, "suricata.yaml"),
        "-o".to_string(),
        files.rule_dir.trim_end_matches('/').to_string(),
        "--disable-conf".to_string(),
        config_path(files, DISABLE_CONF),
        "--drop-conf".to_string(),
        config_path(files, DROP_CONF),
        "--modify-conf".to_string(),
        config_path(files, MODIFY_CONF),
    ]
}

#[cfg(not(test))]
async fn run_suricata_update(args: &[String]) -> Result<(bool, String), String> {
    use tokio::process::Command;

    let run = Command::new("suricata-update")
        .args(args)
        .kill_on_drop(true)
        .output();

    let output = match tokio::time::timeout(UPDATE_TIMEOUT, run).await {
        Err(_) => {
            return Err("suricata-update took longer than 15 minutes and was stopped".to_string());
        }
        Ok(Err(e)) if e.kind() == std::io::ErrorKind::NotFound => {
            return Err(
                "suricata-update is not installed (try: apt install suricata)".to_string(),
            );
        }
        Ok(Err(e)) => return Err(format!("could not run suricata-update: {}", e)),
        Ok(Ok(output)) => output,
    };

    let mut text = String::from_utf8_lossy(&output.stdout).into_owned();
    text.push('\n');
    text.push_str(&String::from_utf8_lossy(&output.stderr));

    Ok((output.status.success(), text))
}

#[cfg(test)]
async fn run_suricata_update(_args: &[String]) -> Result<(bool, String), String> {
    Err("suricata-update is not run in test builds".to_string())
}

/// Downloads the newest signatures and applies the saved overrides to them.
/// Only one update runs at a time. The result is also kept for `last_update`.
pub async fn update_rules(
    pool: &SqlitePool,
    files: &SuricataFiles<'_>,
) -> Result<RuleUpdateStatus, String> {
    let _guard = UPDATE_LOCK
        .try_lock()
        .map_err(|_| "A rule update is already running".to_string())?;

    let outcome = run_update(pool, files).await;

    match outcome {
        Ok(status) => {
            remember(&status);
            Ok(status)
        }
        Err(message) => {
            remember(&RuleUpdateStatus {
                finished_at: now(),
                success: false,
                message: message.chars().take(MAX_MESSAGE_CHARS).collect(),
                total_rules: None,
                enabled_rules: None,
            });
            Err(message)
        }
    }
}

async fn run_update(
    pool: &SqlitePool,
    files: &SuricataFiles<'_>,
) -> Result<RuleUpdateStatus, String> {
    let overrides = IdsRepository::list_overrides(pool)
        .await
        .map_err(|e| e.to_string())?;

    write_override_files(files, &overrides)?;

    fs::create_dir_all(files.rule_dir)
        .map_err(|e| format!("Failed to create {}: {}", files.rule_dir, e))?;

    let (success, output) = run_suricata_update(&update_args(files)).await?;

    if !success {
        return Err(format!("suricata-update failed:\n{}", tail_of(&output)));
    }

    let (total_rules, enabled_rules) = parse_counts(&output);

    Ok(RuleUpdateStatus {
        finished_at: now(),
        success: true,
        message: tail_of(&output),
        total_rules,
        enabled_rules,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicU64, Ordering};

    static COUNTER: AtomicU64 = AtomicU64::new(0);

    fn temp_dir() -> String {
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);

        let dir = std::env::temp_dir().join(format!(
            "iqsoft-rules-test-{}-{}",
            std::process::id(),
            n
        ));

        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();

        dir.to_string_lossy().into_owned()
    }

    fn rule(sid: i64, action: &str) -> IdsRuleOverride {
        IdsRuleOverride {
            id: None,
            sid,
            action: action.into(),
            comment: None,
        }
    }

    fn files_in(dir: &str) -> SuricataFiles<'_> {
        SuricataFiles {
            log_dir: "/var/log/suricata",
            rule_dir: dir,
            rule_file: "suricata.rules",
            config_dir: dir,
            socket: "/run/suricata-command.socket",
        }
    }

    #[test]
    fn each_action_goes_to_its_own_file() {
        let overrides = vec![
            rule(300, "drop"),
            rule(100, "disable"),
            rule(200, "alert"),
            rule(50, "drop"),
        ];

        let disable = render_disable_conf(&overrides);
        let drop = render_drop_conf(&overrides);
        let modify = render_modify_conf(&overrides);

        assert!(disable.contains("\n100\n"));
        assert!(!disable.contains("300"));
        assert!(!disable.contains("200"));

        assert!(drop.contains("\n50\n300\n"));
        assert!(!drop.contains("100"));

        assert!(modify.contains("\n200 \"^(drop|reject)\" \"alert\"\n"));
        assert!(!modify.contains("300"));
    }

    #[test]
    fn no_overrides_give_comment_only_files() {
        for text in [
            render_disable_conf(&[]),
            render_drop_conf(&[]),
            render_modify_conf(&[]),
        ] {
            assert!(text.starts_with('#'));
            assert_eq!(text.lines().count(), 1);
        }
    }

    #[test]
    fn the_override_files_are_written_to_the_config_directory() {
        let dir = temp_dir();
        let files = files_in(&dir);

        write_override_files(&files, &[rule(100, "disable"), rule(200, "drop")]).unwrap();

        let disable = fs::read_to_string(format!("{}/iqsoft-disable.conf", dir)).unwrap();
        let drop = fs::read_to_string(format!("{}/iqsoft-drop.conf", dir)).unwrap();
        let modify = fs::read_to_string(format!("{}/iqsoft-modify.conf", dir)).unwrap();

        assert!(disable.contains("100"));
        assert!(drop.contains("200"));
        assert!(!modify.contains("200"));

        assert!(!Path::new(&format!("{}/iqsoft-disable.conf.tmp", dir)).exists());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn an_empty_signature_file_is_created_but_never_overwritten() {
        let dir = temp_dir();
        let files = files_in(&dir);

        ensure_rules_file(&files).unwrap();

        let path = format!("{}/suricata.rules", dir);
        assert!(Path::new(&path).exists());

        fs::write(&path, "alert tcp any any -> any any (msg:\"x\"; sid:1;)\n").unwrap();
        ensure_rules_file(&files).unwrap();

        assert!(fs::read_to_string(&path).unwrap().contains("sid:1"));

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn only_active_signatures_are_counted() {
        let dir = temp_dir();
        let path = format!("{}/suricata.rules", dir);

        fs::write(
            &path,
            "# a comment\n\
             alert tcp any any -> any any (msg:\"a\"; sid:1;)\n\
             drop udp any any -> any 53 (msg:\"b\"; sid:2;)\n\
             #alert tcp any any -> any any (msg:\"off\"; sid:3;)\n\
             \n\
             reject tcp any any -> any 23 (msg:\"c\"; sid:4;)\n",
        )
        .unwrap();

        assert_eq!(count_rules_in_file(&path).unwrap(), 3);

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn totals_are_read_from_the_update_summary() {
        let output = "19/11/2026 -- 10:00:00 - <Info> -- Loaded 49573 rules.\n\
                      19/11/2026 -- 10:00:01 - <Info> -- Disabled 12 rules.\n\
                      19/11/2026 -- 10:00:02 - <Info> -- Writing rules to /var/lib/suricata/rules/suricata.rules: total: 49573; enabled: 38120; added: 5; removed 0; modified: 2\n";

        assert_eq!(parse_counts(output), (Some(49_573), Some(38_120)));
    }

    #[test]
    fn totals_fall_back_to_the_loaded_line() {
        assert_eq!(parse_counts("-- Loaded 120 rules.\n"), (Some(120), None));
        assert_eq!(parse_counts("nothing useful here\n"), (None, None));
    }

    #[test]
    fn the_message_keeps_only_the_last_lines() {
        let output = (1..=30)
            .map(|n| format!("line {}", n))
            .collect::<Vec<_>>()
            .join("\n");

        let tail = tail_of(&output);

        assert!(tail.ends_with("line 30"));
        assert!(!tail.contains("line 1\n"));
        assert_eq!(tail.lines().count(), MESSAGE_TAIL_LINES);
    }

    #[test]
    fn the_update_command_points_at_the_generated_files() {
        let dir = temp_dir();
        let files = files_in(&dir);
        let args = update_args(&files);

        assert_eq!(args[0], "--no-reload");
        assert!(args.contains(&format!("{}/suricata.yaml", dir)));
        assert!(args.contains(&format!("{}/iqsoft-disable.conf", dir)));
        assert!(args.contains(&format!("{}/iqsoft-drop.conf", dir)));
        assert!(args.contains(&format!("{}/iqsoft-modify.conf", dir)));

        let _ = fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn a_failed_update_is_reported_and_remembered() {
        use crate::database::ids_schema::create_ids_tables;
        use sqlx::sqlite::SqlitePoolOptions;

        let pool = SqlitePoolOptions::new()
            .max_connections(1)
            .connect("sqlite::memory:")
            .await
            .unwrap();
        create_ids_tables(&pool).await.unwrap();

        let dir = temp_dir();
        let files = files_in(&dir);

        let error = update_rules(&pool, &files).await.unwrap_err();
        assert!(error.contains("not run in test builds"));

        let status = last_update().unwrap();
        assert!(!status.success);

        let _ = fs::remove_dir_all(&dir);
    }
}
